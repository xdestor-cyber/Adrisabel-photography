#!/usr/bin/env node
// Renders the hand-drawn storybook illustrations from the promo video
// (video/js/art.js) into static SVG strings for the website, so the site and
// the "Once Upon a Tiny Time" video share one visual language.
// Output: site/src/lib/art.generated.mjs. Run: node site/tools/extract-art.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const ctx = vm.createContext({ console });
for (const f of ['video/js/config.js', 'video/js/art.js']) {
  // top-level const declarations stay in the script scope; expose what we need
  vm.runInContext(fs.readFileSync(path.join(ROOT, f), 'utf8'), ctx, { filename: f });
}
vm.runInContext('globalThis.__ART = ART; globalThis.__COL = COL;', ctx);
const ART = ctx.__ART;
const COL = ctx.__COL;

const tidy = (s) => s.replace(/\s+/g, ' ').replace(/> </g, '><').trim();
const out = {};
for (const k of ['sunshine', 'wonderland', 'fairytale', 'cake', 'seaside', 'twins', 'extraPhotos', 'hookFeet', 'hookBaby', 'wand']) {
  out[k] = tidy(ART[k]);
}
const icons = {};
for (const [k, v] of Object.entries(ART.ICONS)) icons[k] = tidy(v);

// Pixie Dust: a row of waxing moons (one per milestone session).
const moonRow = (phases, labels) => {
  const r = 46, gap = 128, x0 = 64;
  const moons = phases.map((p, i) => ART.moon(x0 + i * gap, 58, r, p) +
    (labels ? `<text class="mlabel" x="${x0 + i * gap}" y="150" text-anchor="middle">${labels[i]}</text>` : '')).join('');
  return tidy(`<svg class="moons" viewBox="0 0 ${x0 * 2 + gap * (phases.length - 1)} ${labels ? 170 : 116}" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">${moons}</svg>`);
};
out.moonsHero = moonRow([0.14, 0.32, 0.5, 0.7, 1]);
out.moonsA = moonRow([0.12, 0.3, 0.5, 0.7, 0.88], [1, 3, 5, 7, 9]);
out.moonsB = moonRow([0.2, 0.4, 0.6, 0.8, 1], [2, 4, 6, 8, 10]);
const spark = (cx, cy, r) => ART.spark(cx, cy, r);
out.sparkPath = spark(23, 23, 20);
out.heartPath = ART.heart(32, 34, 22);

const body = `// GENERATED by site/tools/extract-art.mjs from video/js/art.js — do not edit by hand.
export const COL = ${JSON.stringify(COL, null, 1)};
export const ART = ${JSON.stringify(out, null, 1)};
export const ICONS = ${JSON.stringify(icons, null, 1)};
`;
fs.writeFileSync(path.join(ROOT, 'site/src/lib/art.generated.mjs'), body);
console.log('wrote site/src/lib/art.generated.mjs', (body.length / 1024).toFixed(1), 'KB');
